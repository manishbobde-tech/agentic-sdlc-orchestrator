"""Deterministic mock-LLM fixtures for the golden eval tasks.

The mock coder generates stub modules that satisfy each task's deterministic
checks (file_exists / file_contains), and the mock tester generates pytest
tests that import those stubs — so the whole pipeline runs for real
(file writes + actual pytest execution) with zero network and zero flakiness.
"""
from __future__ import annotations

import json
import re

from sdlc_agents import MockLLM


def _required_files(task: dict) -> list[str]:
    files: list[str] = []
    for check in task["rubric"]["deterministic"]:
        if check["type"] in ("file_exists", "file_contains"):
            if check["path"] not in files:
                files.append(check["path"])
    return files or ["solution.py"]


def _contains_for(task: dict, path: str) -> list[str]:
    return [
        c["text"]
        for c in task["rubric"]["deterministic"]
        if c["type"] == "file_contains" and c["path"] == path
    ]


def _stub_for(text: str) -> str:
    """Turn a required snippet into valid Python containing that snippet."""
    match = re.match(r"\s*def\s+([A-Za-z_][A-Za-z0-9_]*)\s*(\(.*\))?\s*:?\s*$", text)
    if match:
        name, sig = match.group(1), match.group(2) or "(*args, **kwargs)"
        return (
            f"def {name}{sig}:\n"
            '    """Synthetic stub generated by the mock coder."""\n'
            "    return 0\n"
        )
    return f"# requirement: {text}\n"


def build_mock_llm(tasks: list[dict]) -> MockLLM:
    fixtures: dict[tuple[str, str], str] = {}
    for task in tasks:
        tid = task["id"]
        files = _required_files(task)

        code_files: dict[str, str] = {}
        for path in files:
            body = [f'"""{tid}: synthetic module ({path})."""\n']
            required = _contains_for(task, path)
            for text in required:
                body.append(_stub_for(text))
            if not required:
                body.append("VALUE = 42\n")
            code_files[path] = "\n".join(body)

        fixtures[("planner", tid)] = json.dumps(
            {
                "steps": [
                    {"id": 1, "title": f"Design {tid}",
                     "detail": "Produce the module design."},
                    {"id": 2, "title": f"Implement {tid}",
                     "detail": f"Write {', '.join(files)}."},
                    {"id": 3, "title": f"Test {tid}",
                     "detail": "Write and run pytest tests."},
                ],
                "risks": ["Synthetic fixture scope"],
                "acceptance_criteria": [
                    "All deterministic checks pass.",
                    "Pytest suite is green.",
                ],
            }
        )
        fixtures[("architect", tid)] = json.dumps(
            {
                "components": [
                    {"name": path[:-3], "responsibility": f"Implements {tid}"}
                    for path in files
                ],
                "data_model": {},
                "interfaces": [],
                "files_to_create": files,
            }
        )
        fixtures[("coder", tid)] = json.dumps(
            {"files": code_files, "notes": f"Mock implementation for {tid}."}
        )
        fixtures[("reviewer", tid)] = json.dumps(
            {
                "findings": [],
                "verdict": "approved",
                "summary": f"Mock approval for {tid}.",
            }
        )

        test_lines: list[str] = []
        for path in files:
            module = path[:-3] if path.endswith(".py") else path
            for name in re.findall(r"def\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(", code_files[path]):
                test_lines.append(
                    f"def test_{module}_{name}_exists():\n"
                    f"    import {module}\n"
                    f"    assert callable({module}.{name})\n"
                )
        if not test_lines:
            test_lines.append("def test_placeholder():\n    assert True\n")
        test_file = f"test_{tid.replace('-', '_')}.py"
        fixtures[("tester", tid)] = json.dumps(
            {"tests": {test_file: "\n".join(test_lines)}}
        )
    return MockLLM(fixtures=fixtures)
